# 월 × 요일별 일관객 평균 히트맵
# ==================================================

st.divider()

st.header("5. 월 × 요일별 일관객 평균")

st.markdown(
    "각 날짜에서 월과 요일을 추출하여, "
    "월별·요일별 하루 평균 일관객을 히트맵으로 나타냅니다."
)


# --------------------------------------------------
# 월과 요일 추출
# --------------------------------------------------

heatmap_df = df.copy()

heatmap_df["월"] = heatmap_df["날짜"].dt.month


weekday_map = {
    0: "월요일",
    1: "화요일",
    2: "수요일",
    3: "목요일",
    4: "금요일",
    5: "토요일",
    6: "일요일"
}


heatmap_df["요일"] = (
    heatmap_df["날짜"]
    .dt.weekday
    .map(weekday_map)
)


# --------------------------------------------------
# 먼저 날짜별 10위권 일관객 합계 계산
# --------------------------------------------------

daily_audience = (
    heatmap_df
    .groupby(
        ["날짜", "월", "요일"],
        as_index=False
    )["일관객"]
    .sum()
)


# --------------------------------------------------
# 월 × 요일별 하루 평균 계산
# --------------------------------------------------

heatmap_data = (
    daily_audience
    .groupby(
        ["월", "요일"],
        as_index=False
    )["일관객"]
    .mean()
)


# --------------------------------------------------
# 요일 순서 지정
# --------------------------------------------------

weekday_order = [
    "월요일",
    "화요일",
    "수요일",
    "목요일",
    "금요일",
    "토요일",
    "일요일"
]


heatmap_data["요일"] = pd.Categorical(
    heatmap_data["요일"],
    categories=weekday_order,
    ordered=True
)


heatmap_data = heatmap_data.sort_values(
    ["월", "요일"]
)


# --------------------------------------------------
# 히트맵
# --------------------------------------------------

fig5 = px.density_heatmap(
    heatmap_data,
    x="요일",
    y="월",
    z="일관객",
    category_orders={
        "요일": weekday_order,
        "월": list(range(1, 13))
    },
    color_continuous_scale="Blues",
    text_auto=".3s",
    title="월 × 요일별 10위권 일관객 평균",
    labels={
        "요일": "요일",
        "월": "월",
        "일관객": "일평균 일관객"
    }
)


# --------------------------------------------------
# 그래프 설정
# --------------------------------------------------

fig5.update_layout(
    height=600,
    xaxis_title="요일",
    yaxis_title="월",
    margin=dict(
        l=20,
        r=20,
        t=60,
        b=20
    ),
    coloraxis_colorbar_title="일평균 일관객"
)


fig5.update_yaxes(
    tickmode="linear",
    dtick=1,
    autorange="reversed"
)


# --------------------------------------------------
# 마우스를 올렸을 때 표시
# --------------------------------------------------

fig5.update_traces(
    hovertemplate=(
        "<b>%{y}월 %{x}</b><br>"
        "<b>일평균 일관객</b>: %{z:,.0f}명"
        "<extra></extra>"
    )
)


st.plotly_chart(
    fig5,
    use_container_width=True
)


# --------------------------------------------------
# 그래프로 알 수 있는 것
# --------------------------------------------------

st.markdown("### 💡 이 그래프로 알 수 있는 것")

st.info(
    "월과 요일에 따른 하루 평균 관객 규모를 비교하여 "
    "특정 시기와 요일에 영화 관객이 많이 몰리는 경향을 확인할 수 있습니다."
)
